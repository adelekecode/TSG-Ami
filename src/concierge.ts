import { z } from "zod";
import { ApiError, lookupUnit } from "./maintenance";
import { execute, tenancy, DomainError } from "./domain";

export const verifyResidentSchema = z.object({
  unit_id: z.string().trim().min(2).max(32),
  demo_code: z.string().trim().min(4).max(64),
});
export const startPaymentSchema = z.object({
  session_token: z.string().min(20),
  invoice_id: z.string().min(4).max(80),
  confirmed: z.literal(true),
});
export const complaintSchema = z.object({
  session_token: z.string().min(20),
  category: z.enum(["noise", "security", "cleanliness", "management", "other"]),
  description: z.string().trim().min(10).max(1000),
  idempotency_key: z.string().min(8).max(128),
});
export type VerifyResidentInput = z.infer<typeof verifyResidentSchema>;
export type StartPaymentInput = z.infer<typeof startPaymentSchema>;
export type ComplaintInput = z.infer<typeof complaintSchema>;

interface ResidentRow {
  id: string;
  display_name: string;
  email: string | null;
  unit_id: string;
  demo_code_hash: string;
  active: number;
}
interface InvoiceRow {
  id: string;
  resident_id: string;
  kind: string;
  description: string;
  amount_kobo: number;
  currency: string;
  due_date: string;
  status: string;
  paid_at: string | null;
  paid_reference: string | null;
}
interface PaymentRow {
  reference: string;
  invoice_id: string;
  resident_id: string;
  status: string;
  checkout_url: string | null;
  created_at: string;
  updated_at: string;
}
export interface PaystackEnv {
  DB: D1Database;
  PAYSTACK_SECRET_KEY?: string;
}

const now = () => new Date().toISOString();
const formatInvoice = (i: InvoiceRow) => ({
  invoice_id: i.id,
  type: i.kind,
  description: i.description,
  currency: i.currency,
  amount_kobo: i.amount_kobo,
  amount_ngn: (i.amount_kobo / 100).toFixed(2),
  due_date: i.due_date,
  status: i.status,
  paid_at: i.paid_at,
  payment_reference: i.paid_reference,
});
export async function verifyResident(
  db: D1Database,
  input: VerifyResidentInput,
) {
  const data = verifyResidentSchema.parse(input);
  const result = await execute({ DB: db }, "resolve_resident", {
    unit_id: data.unit_id.trim().toUpperCase(),
    onboarding_code: data.demo_code,
  }) as { resident_token: string };
  const r = await verifiedResident(db, result.resident_token);
  const unit = await lookupUnit(db, r.unit_id);
  return {
    verified: true,
    session_token: result.resident_token,
    expires_in_minutes: 1440,
    resident: { name: r.display_name, unit_id: r.unit_id, property: unit.property_name },
  };
}

async function verifiedResident(
  db: D1Database,
  token: string,
): Promise<ResidentRow> {
  if (typeof token !== "string" || token.length < 20)
    throw new ApiError(
      401,
      "VERIFICATION_REQUIRED",
      "Please verify your demo tenancy first.",
    );
  const t = await tenancy({ DB: db }, token).catch((error: unknown) => {
    if (error instanceof DomainError)
      throw new ApiError(error.status, "SESSION_EXPIRED", "Your verified session has expired. Please verify again.");
    throw error;
  });
  const resident = await db.prepare(
    "SELECT t.id, r.preferred_name AS display_name, r.email, t.unit_id, t.onboarding_hash AS demo_code_hash, t.active FROM tenancies t JOIN residents r ON r.id=t.resident_id WHERE t.id=?",
  ).bind(t.id).first<ResidentRow>();
  if (!resident) throw new ApiError(401, "SESSION_EXPIRED", "Please verify again.");
  return resident;
}

export async function myProfile(db: D1Database, token: string) {
  const r = await verifiedResident(db, token);
  const unit = await lookupUnit(db, r.unit_id);
  return {
    name: r.display_name,
    unit_id: r.unit_id,
    property: unit.property_name,
    building: unit.building,
  };
}
export async function myInvoices(db: D1Database, token: string) {
  const r = await verifiedResident(db, token);
  const { results } = await db
    .prepare("SELECT * FROM invoices WHERE resident_id=? ORDER BY due_date, id")
    .bind(r.id)
    .all<InvoiceRow>();
  return { invoices: results.map(formatInvoice) };
}
async function ownedInvoice(
  db: D1Database,
  residentId: string,
  invoiceId: string,
): Promise<InvoiceRow> {
  const i = await db
    .prepare("SELECT * FROM invoices WHERE id=? AND resident_id=?")
    .bind(invoiceId, residentId)
    .first<InvoiceRow>();
  if (!i)
    throw new ApiError(
      404,
      "INVOICE_NOT_FOUND",
      "No invoice found for this verified resident.",
    );
  return i;
}
// Give Chord both the raw provider URL and a ready-to-send WhatsApp-friendly message.
// The URL is NEVER generated by the model or derived from the invoice ID.
export function paymentLinkResult(
  invoice: InvoiceRow,
  reference: string,
  checkoutUrl: string,
  reused = false,
) {
  const paystackUrl = new URL(checkoutUrl);
  if (
    paystackUrl.protocol !== "https:" ||
    paystackUrl.hostname !== "checkout.paystack.com"
  )
    throw new ApiError(
      502,
      "PAYSTACK_INVALID_CHECKOUT_URL",
      "Unexpected checkout URL from payment provider.",
    );
  const amount = (invoice.amount_kobo / 100).toLocaleString("en-NG", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  return {
    invoice: formatInvoice(invoice),
    status: "pending" as const,
    provider: "paystack" as const,
    environment: "test" as const,
    reference,
    checkout_url: checkoutUrl,
    reused,
    chat_message: [
      `Your Paystack TEST checkout link for ${invoice.description} (₦${amount}):`,
      "",
      checkoutUrl,
      "",
      `Payment reference: ${reference}`,
      "🧪 TEST MODE — no real money will be collected.",
      'Open the link to try the checkout. When you are done, come back and say "Check my payment" so I can verify its status.',
    ].join("\n"),
    message: "Link generated, payment NOT confirmed.",
  };
}
async function paystackCall(
  env: PaystackEnv,
  path: string,
  init?: RequestInit,
) {
  if (!env.PAYSTACK_SECRET_KEY?.startsWith("sk_test_"))
    throw new ApiError(
      503,
      "TEST_KEY_REQUIRED",
      "Paystack test key is missing. Live keys are blocked in this exercise.",
    );
  let response: Response;
  try {
    response = await fetch(`https://api.paystack.co${path}`, {
      ...init,
      headers: {
        Authorization: `Bearer ${env.PAYSTACK_SECRET_KEY}`,
        ...(init?.body ? { "Content-Type": "application/json" } : {}),
      },
    });
  } catch {
    throw new ApiError(
      502,
      "PAYSTACK_UNAVAILABLE",
      "Unable to reach the payment provider.",
    );
  }
  const data = (await response.json().catch(() => null)) as Record<
    string,
    unknown
  > | null;
  if (!response.ok || !data?.status)
    throw new ApiError(
      502,
      "PAYSTACK_ERROR",
      "Paystack could not process this request.",
    );
  return data.data as Record<string, unknown>;
}

export async function startPayment(
  env: PaystackEnv,
  input: StartPaymentInput,
  origin: string,
) {
  const { session_token, invoice_id } = startPaymentSchema.parse(input);
  if (!env.PAYSTACK_SECRET_KEY?.startsWith("sk_test_"))
    throw new ApiError(503, "TEST_KEY_REQUIRED", "Paystack test key is missing. Live keys are blocked in this exercise.");
  const r = await verifiedResident(env.DB, session_token);
  const i = await ownedInvoice(env.DB, r.id, invoice_id);
  if (i.status === "paid")
    return {
      invoice: formatInvoice(i),
      status: "already_paid",
      message: "This invoice is already paid.",
    };
  if (i.currency !== "NGN")
    throw new ApiError(409, "UNSUPPORTED_CURRENCY", "Test checkout currently supports NGN invoices only.");
  const active = await env.DB.prepare(
    `SELECT * FROM payment_attempts WHERE invoice_id=? AND status IN ('initializing','pending') ORDER BY created_at DESC LIMIT 1`,
  )
    .bind(i.id)
    .first<PaymentRow>();
  if (active) {
    if (active.status === "pending" && active.checkout_url)
      return paymentLinkResult(i, active.reference, active.checkout_url, true);
    throw new ApiError(
      409,
      "PAYMENT_INITIALIZING",
      "A payment link is currently being generated. Please retry shortly.",
    );
  }
  if (!r.email)
    throw new ApiError(409, "PAYMENT_EMAIL_REQUIRED", "A verified billing email must be configured before checkout.");
  const reference = `AMI-${crypto.randomUUID()}`;
  const timestamp = now();
  const inserted = await env.DB.prepare(
    `INSERT OR IGNORE INTO payment_attempts(reference,invoice_id,resident_id,status,created_at,updated_at)
    VALUES (?,?,?,'initializing',?,?)`,
  )
    .bind(reference, i.id, r.id, timestamp, timestamp)
    .run();
  if (inserted.meta.changes !== 1)
    throw new ApiError(
      409,
      "PAYMENT_IN_PROGRESS",
      "An invoice payment is already in progress.",
    );
  try {
    const safeOrigin = new URL(origin).origin;
    const result = await paystackCall(env, "/transaction/initialize", {
      method: "POST",
      body: JSON.stringify({
        email: r.email,
        amount: String(i.amount_kobo),
        currency: i.currency,
        reference,
        callback_url: `${safeOrigin}/payments/return`,
        metadata: JSON.stringify({
          invoice_id: i.id,
          kind: i.kind,
          environment: "tsg-labs-demo",
        }),
      }),
    });
    if (
      result.reference !== reference ||
      typeof result.authorization_url !== "string"
    )
      throw new ApiError(
        502,
        "PAYSTACK_INVALID_RESPONSE",
        "Unexpected response from Paystack.",
      );
    // Validate the returned URL before storing it or showing it to the resident.
    const chatResult = paymentLinkResult(
      i,
      reference,
      result.authorization_url,
    );
    await env.DB.prepare(
      `UPDATE payment_attempts SET status='pending', checkout_url=?, updated_at=? WHERE reference=? AND status='initializing'`,
    )
      .bind(chatResult.checkout_url, now(), reference)
      .run();
    return chatResult;
  } catch (e) {
    await env.DB.prepare(
      `UPDATE payment_attempts SET status='error',updated_at=? WHERE reference=? AND status='initializing'`,
    )
      .bind(now(), reference)
      .run()
      .catch(() => {});
    throw e;
  }
}

async function verifyAttempt(env: PaystackEnv, attempt: PaymentRow) {
  const invoice = await ownedInvoice(
    env.DB,
    attempt.resident_id,
    attempt.invoice_id,
  );
  const result = await paystackCall(
    env,
    `/transaction/verify/${encodeURIComponent(attempt.reference)}`,
  );
  // Verify all essential fields, including provider environment and money amount, before crediting an invoice.
  if (
    result.reference !== attempt.reference ||
    result.domain !== "test" ||
    result.currency !== invoice.currency ||
    result.amount !== invoice.amount_kobo ||
    result.status === undefined
  )
    throw new ApiError(
      409,
      "PAYMENT_MISMATCH",
      "Transaction details do not match the invoice. Escalate for manual review.",
    );
  if (result.status === "success") {
    const timestamp = now();
    await env.DB.batch([
      env.DB.prepare(
        `UPDATE payment_attempts SET status='success',updated_at=? WHERE reference=?`,
      ).bind(timestamp, attempt.reference),
      env.DB.prepare(
        `UPDATE invoices SET status='paid',paid_at=?,paid_reference=? WHERE id=? AND status='unpaid'`,
      ).bind(timestamp, attempt.reference, invoice.id),
    ]);
  } else if (["failed", "abandoned"].includes(String(result.status))) {
    await env.DB.prepare(
      `UPDATE payment_attempts SET status=?,updated_at=? WHERE reference=? AND status NOT IN ('success')`,
    )
      .bind(result.status, now(), attempt.reference)
      .run();
  }
  const latest = await ownedInvoice(
    env.DB,
    attempt.resident_id,
    attempt.invoice_id,
  );
  return {
    invoice: formatInvoice(latest),
    payment_status: result.status,
    reference: attempt.reference,
    verified_paid: latest.paid_reference === attempt.reference,
    duplicate_payment_review:
      latest.status === "paid" &&
      latest.paid_reference !== attempt.reference &&
      result.status === "success",
  };
}
export async function getPaymentStatus(
  env: PaystackEnv,
  token: string,
  invoiceId: string,
) {
  const r = await verifiedResident(env.DB, token);
  const i = await ownedInvoice(env.DB, r.id, invoiceId);
  const attempt = await env.DB.prepare(
    "SELECT * FROM payment_attempts WHERE invoice_id=? ORDER BY created_at DESC LIMIT 1",
  )
    .bind(i.id)
    .first<PaymentRow>();
  if (!attempt)
    return {
      invoice: formatInvoice(i),
      payment_status: "not_started",
      verified_paid: false,
    };
  if (attempt.status === "success" && i.paid_reference === attempt.reference)
    return {
      invoice: formatInvoice(i),
      payment_status: "success",
      reference: attempt.reference,
      verified_paid: true,
    };
  return verifyAttempt(env, attempt);
}
export async function applySuccessfulWebhook(
  env: PaystackEnv,
  reference: string,
) {
  const attempt = await env.DB.prepare(
    "SELECT * FROM payment_attempts WHERE reference=?",
  )
    .bind(reference)
    .first<PaymentRow>();
  if (!attempt) return { ignored: true, reason: "UNKNOWN_REFERENCE" };
  return verifyAttempt(env, attempt);
}
export async function validatePaystackWebhook(
  rawBody: string,
  signature: string | null,
  secret: string | undefined,
): Promise<boolean> {
  if (
    !secret?.startsWith("sk_test_") ||
    !signature ||
    !/^[0-9a-fA-F]{128}$/.test(signature)
  )
    return false;
  const key = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(secret),
    { name: "HMAC", hash: "SHA-512" },
    false,
    ["verify"],
  );
  const bytes = new Uint8Array(
    signature.match(/.{2}/g)!.map((x) => parseInt(x, 16)),
  );
  return crypto.subtle.verify(
    "HMAC",
    key,
    bytes,
    new TextEncoder().encode(rawBody),
  );
}
export async function createComplaint(db: D1Database, input: ComplaintInput) {
  const data = complaintSchema.parse(input);
  const r = await verifiedResident(db, data.session_token);
  const existing = await db
    .prepare("SELECT * FROM complaints WHERE idempotency_key=?")
    .bind(data.idempotency_key)
    .first<{
      id: string;
      resident_id: string;
      description: string;
      category: string;
      status: string;
    }>();
  if (existing) {
    if (
      existing.resident_id !== r.id ||
      existing.description !== data.description ||
      existing.category !== data.category
    )
      throw new ApiError(
        409,
        "IDEMPOTENCY_CONFLICT",
        "This complaint request key was already used.",
      );
    return {
      complaint_id: existing.id,
      status: existing.status,
      created: false,
    };
  }
  const id = `CMP-${crypto.randomUUID()}`;
  await db
    .prepare(
      `INSERT OR IGNORE INTO complaints(id,resident_id,unit_id,category,description,status,idempotency_key,created_at)
    VALUES (?,?,?,?,?,'open',?,?)`,
    )
    .bind(
      id,
      r.id,
      r.unit_id,
      data.category,
      data.description,
      data.idempotency_key,
      now(),
    )
    .run();
  const saved = await db
    .prepare("SELECT * FROM complaints WHERE idempotency_key=?")
    .bind(data.idempotency_key)
    .first<{
      id: string;
      resident_id: string;
      description: string;
      category: string;
      status: string;
    }>();
  if (
    !saved ||
    saved.resident_id !== r.id ||
    saved.description !== data.description ||
    saved.category !== data.category
  )
    throw new ApiError(
      409,
      "IDEMPOTENCY_CONFLICT",
      "Unable to confirm complaint creation.",
    );
  return {
    complaint_id: saved.id,
    status: saved.status,
    created: saved.id === id,
  };
}
