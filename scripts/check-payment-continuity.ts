import assert from "node:assert/strict";
import {readFileSync,writeFileSync} from "node:fs";
import {createInterface} from "node:readline";
import {Client} from "@modelcontextprotocol/sdk/client/index.js";
import {StreamableHTTPClientTransport} from "@modelcontextprotocol/sdk/client/streamableHttp.js";
const base="https://ami-worker.oluwafemiadeleke13.workers.dev";
const key=(process.env.API_KEY??readFileSync(".dev.vars","utf8").match(/^API_KEY=(.+)$/m)?.[1])?.trim().replace(/^(["'])(.*)\1$/,"$2");
assert(key,"Private integration key required");
const client=new Client({name:"ami-v7-direct-mcp-acceptance",version:"1.0.0"});
const primaryCalls:Record<string,number>={};
const call=async(name:string,args:Record<string,unknown>,scope="primary",isError=false)=>{
  if(scope==="primary")primaryCalls[name]=(primaryCalls[name]??0)+1;
  const result=await client.callTool({name,arguments:args});
  assert.equal(Boolean(result.isError),isError,`Unexpected outcome for ${name}`);
  return JSON.parse((result.content as {text:string}[])[0].text);
};
const timeout=setTimeout(()=>{console.error("Acceptance wait timed out without exposing capabilities.");process.exit(1);},600000);
try {
  await client.connect(new StreamableHTTPClientTransport(new URL(base+"/mcp"),{requestInit:{headers:{Authorization:`Bearer ${key}`}}}));
  const current=(await client.listTools()).tools;
  const previous=JSON.parse(readFileSync(".wrangler/v7-baseline-tools.json","utf8")) as typeof current;
  assert.equal(previous.length,19);assert.equal(current.length,21);
  for(const tool of previous)assert.deepEqual(current.find(t=>t.name===tool.name),tool,`Existing definition changed: ${tool.name}`);
  const options=await call("find_demo_profiles",{name:"Seun"});
  const chosen=options.profiles.find((p:any)=>p.demo_profile_id==="demo_seun_b101");assert(chosen);
  const opened=await call("open_demo_profile",{demo_profile_id:chosen.demo_profile_id,confirmed:true});
  const session={session_token:opened.session_token};
  assert.equal((await call("get_my_profile",session)).unit_id,"B101");
  const bills=(await call("get_my_invoices",session)).invoices;
  const bill=bills.find((i:any)=>i.type==="utility"&&i.status==="unpaid")??bills.find((i:any)=>i.status==="unpaid");
  assert(bill,"An unpaid fictional bill is required for this hosted test");
  const linkInput={...session,invoice_id:bill.invoice_id,confirmed:true};
  const payment=await call("create_payment_link",linkInput);
  assert.equal(payment.environment,"test");
  assert.equal(payment.invoice.amount_kobo,bill.amount_kobo);
  assert.equal(new URL(payment.checkout_url).hostname,"checkout.paystack.com");
  assert(!/\p{Extended_Pictographic}/u.test(payment.chat_message));
  const reused=await call("create_payment_link",linkInput);
  assert.equal(reused.reused,true);assert.equal(reused.reference,payment.reference);assert.equal(reused.checkout_url,payment.checkout_url);
  const before=await call("check_latest_payment",session);
  assert.equal(before.found,true);assert.equal(before.context_source,"active_session");assert.equal(before.reference,payment.reference);assert.equal(before.verified_paid,false);
  const metadata={source:"direct MCP acceptance client, not Chord",profile_id:chosen.demo_profile_id,invoice_id:bill.invoice_id,description:bill.description,amount_kobo:bill.amount_kobo,reference:payment.reference,checkout_url:payment.checkout_url,before_status:before.payment_status,tools:current.length,unchanged_definitions:previous.length};
  writeFileSync(".wrangler/v7-live-payment.json",JSON.stringify(metadata,null,2),{mode:0o600});
  console.log("CHECKOUT_READY "+JSON.stringify(metadata));
  console.log("Private resident capability remains only in process memory. Complete the TEST checkout, then send verify.");
  const lines=createInterface({input:process.stdin});
  let acceptanceComplete=false;
  for await(const line of lines) {
    if(line.trim()!=="verify")continue;
    const result=await call("check_latest_payment",session);
    assert.equal(result.reference,payment.reference);assert.equal(result.verified_paid,true);assert.equal(result.context_source,"active_session");
    assert.equal((await call("get_my_invoices",session)).invoices.find((i:any)=>i.invoice_id===bill.invoice_id).status,"paid");
    assert.equal((await call("check_latest_payment",session)).verified_paid,true);
    assert.equal((await call("create_payment_link",linkInput)).status,"already_paid");
    assert.equal(primaryCalls.open_demo_profile,1);assert.equal(primaryCalls.find_demo_profiles,1);
    // Explicit separate-session recovery and wrong-account scenarios.
    const recovery=await call("open_demo_profile",{demo_profile_id:chosen.demo_profile_id,confirmed:true},"recovery");
    const recovered=await call("check_latest_payment",{session_token:recovery.session_token},"recovery");
    assert.equal(recovered.context_source,"resident_history");assert.equal(recovered.reference,payment.reference);assert.equal(recovered.verified_paid,true);
    const other=await call("open_demo_profile",{demo_profile_id:"demo_ada_c302",confirmed:true},"isolation");
    const otherResult=await call("check_latest_payment",{session_token:other.session_token},"isolation");
    assert.notEqual(otherResult.reference,payment.reference);
    await call("check_payment_status",{session_token:other.session_token,invoice_id:bill.invoice_id},"isolation",true);
    const denied=await call("check_latest_payment",{session_token:"invalid-private-resident-session"},"isolation",true);
    assert.equal(denied.error,"SESSION_EXPIRED");
    const originalDiagnosis=JSON.parse(readFileSync(".wrangler/v7-seun-diagnosis.json","utf8"));
    const originalAccount=await call("open_demo_profile",{demo_profile_id:"demo_seun_a204",confirmed:true},"original-diagnosis");
    const originalRecovery=await call("check_latest_payment",{session_token:originalAccount.session_token},"original-diagnosis");
    assert.equal(originalRecovery.reference,originalDiagnosis.reference);assert.equal(originalRecovery.verified_paid,true);
    assert.equal(originalRecovery.context_source,"resident_history");
    const rest=await fetch(base+"/v1/payments/latest",{headers:{Authorization:`Bearer ${key}`,"X-Demo-Session":session.session_token}});
    assert.equal(rest.status,200);assert.equal((await rest.json() as any).reference,payment.reference);
    const outcome={...metadata,verified_paid:result.verified_paid,payment_status:result.payment_status,invoice_status:result.invoice.status,session_source:result.context_source,new_session_source:recovered.context_source,wrong_account_denied:true,original_incident_reference_recovered:originalRecovery.reference,primary_calls:primaryCalls};
    writeFileSync(".wrangler/v7-live-outcome.json",JSON.stringify(outcome,null,2),{mode:0o600});
    console.log("ACCEPTANCE_PASSED "+JSON.stringify(outcome));
    acceptanceComplete=true;
    lines.close();break;
  }
  assert(acceptanceComplete,"Input closed before hosted verification; acceptance is incomplete. Run with an interactive terminal.");
} finally {clearTimeout(timeout);await client.close();}
